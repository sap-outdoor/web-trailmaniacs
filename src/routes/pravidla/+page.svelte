						Každý závodník závodu svojí přihláškou a prezencí před startem potvrzuje, že se
						dostatečně seznámil se všemi pravidly a souhlasí s nimi:
						<ol>
							<li>
								Je si vědom důsledků spojených se svojí účastí v závodě, kterého se účastní na
								vlastní odpovědnost a nebezpečí. Není oprávněn požadovat po pořadateli finanční
								plnění nebo uplatňovat jakékoliv jiné nároky za zranění či jiné škody, které utrpí v
								souvislosti se sportovní akcí.

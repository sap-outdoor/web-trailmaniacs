								odložené věci.
							</li>
							<li>
								Souhlasí, aby jeho účast a sportovní výkon v závodě byly pořadatelem nebo osobou
								pořadatelem zmocněnou audiovizuálně zaznamenávány a zároveň uděluje svolení, aby
								tyto záznamy vytvořené před, během a po akci mohly být použity všemi způsoby
								uvedenými v §12 odst. 4 autorského zákona za účelem prezentace tohoto závodu, a to
								bez nároku na honorář.
							</li>
							<li>
								Zavazuje se k dodržování pravidel silničního provozu při pohybu po pozemních
								komunikacích dle zákona č. 361/2000 Sb., o provozu na pozemních komunikacích a o
								změnách některých zákonů (zákon o silničním provozu), ve znění pozdějších předpisů.
							</li>
						</ol>
					</li>
					<li>
						Závodník je povinen poskytnout první pomoc v případě, že je to nutné a žádá si to
						zdravotní stav jiného závodníka.
					</li>
					<li>
						Do závodu smí nastoupit pouze závodníci, kteří splňují bez výhrad pravidla závodu, jsou
						v dobrém zdravotním stavu, nejsou pod vlivem alkoholu či jiných omamných látek.
						Pořadatel si vyhrazuje právo nepustit na start nebo zastavit v závodě každého závodníka,
						který bude vykazovat známky přílišné únavy či vyčerpání a mohlo by dojít k ohrožení jeho
						zdraví.
					</li>
					<li>
						Do závodu smí nastoupit pouze závodníci registrovaní na oficiálních stránkách
						trailmaniacs.cz přes registrační formulář, či po individuální domluvě s pořadatelem.
					</li>
					<li>
						Online registrace se uzavírají 20. 10. 2027. Po tomto datu je možné se přihlásit jen se
						souhlasem pořadatele závodu. Maximální počet startujících závodníků je 500.
					</li>
					<li>
						Startovné se hradí dopředu poukázáním na účet č. 2000631637/2010. Při platbě uveďte

						Pořadatel závodu si vyhrazuje právo registraci uzavřít nebo upravit podmínky, pokud to
						bude vyžadovat situace.
					</li>
					<li>
						Zaplacené startovné se nevrací ani nepřevádí na další ročník. Je ale možné jej prodat či
						převést na jiného účastníka nejpozději 48h před akcí.
					</li>
					<li>
						V případě nějaké nenadálé události (kalamity, život ohrožujícího stavu) si pořadatel
						vyhrazuje právo závod přerušit, uzavřít nebo zrušit. V tomto případě se startovné
						nevrací. Je možnost jeho převodu na další závod či ročník.
					</li>
					<li>
						Závodník nesmí přijmout jakoukoliv pomoc mimo vyhrazené občerstvovací prostory. Výjimkou
						jsou pouze případy, kdy je nutné poskytnout první pomoc.
					</li>
					<li>
						Každý závodník musí mít u sebe povinnou výbavu. Pořadatel si vyhrazuje právo na
						namátkové kontroly i během závodu. Absence nebo případně nekompletnost povinné výbavy
						znamená penalizaci.
					</li>
					<li>
						Závodník postupuje po turistických značkách, lesních cestách a značené trase. Na trati
						budou označeny kontrolní body, na kterých závodníci budou značit do průkazky průchod
						tímto kontrolním bodem. Pokud neprojdou celou trasu, jsou automaticky diskvalifikováni.
					</li>
					<li>
						Je zakázáno používat k přesunu jakékoliv cizí předměty (auto, motocykl, autobus,
						traktor, vlak, brusle, koně, atd.).
					</li>
					<li>
						Povinná výbava se skládá z:
						<ol>
							<li>NRC (alu folie)</li>
							<li>mobilní telefon</li>
							<li>nepromokavá bunda</li>
							<li>čelovka</li>
							<li>1x vlastní nádoba/kelímek na pití (pro použití na občerstvovacích stanicích)</li>
						</ol>
					</li>
					<li>
						Chybějící povinné vybavení znamená časovou penalizaci 15 minut za každý chybějící kus.
					</li>
					<li>
						Soutěžní disciplíny:
						<ol>
							<li>
								<strong>Celkové pořadí</strong> – hodnotí se vždy 3 nejrychlejší závodníci v kategorii
								s nejlepším dosaženým časem při absolvováním celé trati.
							</li>
							<li>
								<strong>Rychlostní úseky</strong> – hodnotí se vždy první závodník v daném úseku s absolutně
								nejrychlejším časem na trati 61 a první závodník v daném úseku s absolutně nejrychlejším
								časem na trati 47. Do této disciplíny jsou zařazeni pouze ti závodníci, kteří nepřekročí
								130% času vítěze.
							</li>
						</ol>
					</li>
					<li>
						Pro všechny závodníky hodnocené na stupních vítězů nebo na daném rychlostním úseku, jsou
						připraveny prize money nebo věcné ceny.
						<ol>
							<li>
								V rychlostních úsecích se hodnotí vždy <em
									>první závodník v kategorii mužů a žen na trati 61 a 47</em
								>.
							</li>
							<li>
								Celkově jsou vyhlášeny <em>první 3 závodníci v kategorii</em> dle dosaženého času s absolvovanou
								celou tratí.
							</li>
							<li>
								Prize money za celkové pořadí jsou vypláceny jen v případě, že je na startu závodu
								minimálně 50 mužů nebo 30 žen startujících v kategorii.
							</li>
